README_NOTES = [
    "Source Data for the QTrack manuscript. Each sheet contains the numerical values "
    "behind the plotted elements of one figure, organized in blocks labeled by panel.",
    "",
    "Notes:",
    "- Figure 1 is a conceptual illustration with no plotted data, so it has no sheet.",
    "- Units are given in the column headers (um = micrometers, s = seconds, "
    "um2_per_s = um^2/s, pct = percent).",
    "- Histogram panels are provided as binned probability densities exactly as plotted "
    "(bin centers and per-bin density).",
    "- Image blocks are pixel matrices in heatmap orientation: the first row holds the x "
    "coordinates of the pixel centers, the first column the y coordinates.",
    "- Empty cells correspond to values that are not available (plotted as gaps).",
    "- These files are generated by the figure scripts at "
    "https://github.com/LabPresse/qtrack-paper-figures from the precomputed results "
    "archived at https://doi.org/10.5281/zenodo.20656381.",
    "",
    "Sheets:",
]

BOLD = Font(bold=True)
TITLE = Font(bold=True, size=12)


def parse_value(s):
    s = s.strip()
    if s == "" or s.lower() == "nan":
        return None
    try:
        return int(s)
    except ValueError:
        pass
    try:
        return float(s)
    except ValueError:
        return s


def block_title(stem):
    m = re.match(r"^(row\d+|abc|ab|ef|[a-h])_(.*)$", stem)
    if m:
        panel, rest = m.groups()
        rest = rest.replace("_", " ")
        if panel.startswith("row"):
            return f"Row {panel[3:]}: {rest}"
        return f"Panel {panel}: {rest}"
    return stem.replace("_", " ")


def styled(ws, value, font):
    cell = WriteOnlyCell(ws, value=value)
    cell.font = font
    return cell


def main():
    if not SOURCE_DIR.is_dir():
        sys.exit(f"{SOURCE_DIR} not found - run the figure scripts first.")

    wb = Workbook(write_only=True)

    readme = wb.create_sheet("README")
    readme.column_dimensions["A"].width = 110
    for line in README_NOTES:
        readme.append([styled(readme, line, BOLD) if line in ("Notes:", "Sheets:") else line])

    missing = []
    for folder, sheet_name, description in FIGURES:
        fig_dir = SOURCE_DIR / folder
        csvs = sorted(fig_dir.glob("*.csv")) if fig_dir.is_dir() else []
        if not csvs:
            missing.append(folder)
            continue
        readme.append([f"{sheet_name}: {description}"])

        ws = wb.create_sheet(sheet_name)
        ws.append([styled(ws, sheet_name, TITLE)])
        ws.append([])
        for path in csvs:
            ws.append([styled(ws, block_title(path.stem), BOLD)])
            with open(path, newline="") as fh:
                reader = csv.reader(fh)
                header = next(reader, None)
                if header is not None:
                    ws.append([styled(ws, h, BOLD) for h in header])
                for row in reader:
                    ws.append([parse_value(v) for v in row])
            ws.append([])
        print(f"{sheet_name}: {len(csvs)} blocks")

    if missing:
        print(f"WARNING: no CSVs found for: {', '.join(missing)}", file=sys.stderr)

    wb.save(OUT_PATH)
    size_mb = OUT_PATH.stat().st_size / 1e6
    print(f"Wrote {OUT_PATH} ({size_mb:.1f} MB)")


if __name__ == "__main__":
    main()
